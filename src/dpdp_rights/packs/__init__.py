"""Domain packs: ready-made purposes, legal holds, policy rules, identifier patterns, rights settings,
inventories, discovery questions and offline scenario tests for a sector (docs/domain-packs.md).

    dpdp-rights packs list
    dpdp-rights packs show insurance
    dpdp-rights packs init insurance --output ~/engagements/acme [--base config/dpdp.production.aws.yaml]
    dpdp-rights packs test insurance            # or all; --config <client dpdp.yaml> --scenarios <file>
"""
from __future__ import annotations

import copy
import shutil
from pathlib import Path

import yaml

PACK_DIR = Path(__file__).parent
FILES = ("inventory.yaml", "scenarios.yaml", "questions.md", "README.md")


def available() -> list[str]:
    return sorted(p.name for p in PACK_DIR.iterdir() if (p / "pack.yaml").exists())


def load(pack_id: str) -> dict:
    p = PACK_DIR / pack_id / "pack.yaml"
    if not p.exists():
        raise KeyError(f"unknown pack '{pack_id}'; available: {', '.join(available())}")
    data = yaml.safe_load(p.read_text(encoding="utf-8"))
    data["_dir"] = str(p.parent)
    return data


def scenarios(pack_id: str) -> dict:
    return yaml.safe_load((PACK_DIR / pack_id / "scenarios.yaml").read_text(encoding="utf-8")) or {}


def merge(base: dict, fragment: dict) -> dict:
    """The pack's settings on top of a base config: purposes replaced, policy rules first, PII patterns and
    rights settings added; everything else (provider, vault, connectors, auth) kept from the base."""
    out = copy.deepcopy(base)
    out["purposes"] = copy.deepcopy(fragment.get("purposes", []))
    pol = dict(out.get("policy") or {})
    fp = fragment.get("policy") or {}
    for k in ("default_action", "aggregate_k_threshold"):
        if k in fp:
            pol[k] = fp[k]
    pol["rules"] = list(fp.get("rules", [])) + [r for r in pol.get("rules", []) if r not in fp.get("rules", [])]
    out["policy"] = pol
    pii = dict(out.get("pii") or {})
    pii["patterns"] = list(pii.get("patterns", [])) + list((fragment.get("pii") or {}).get("patterns", []))
    out["pii"] = pii
    rights = dict(out.get("rights") or {})
    fr = fragment.get("rights") or {}
    for k, v in fr.items():
        if k == "recipients":
            seen = {r.get("store") for r in rights.get("recipients", []) or []}
            rights["recipients"] = list(rights.get("recipients") or []) + [r for r in v if r.get("store") not in seen]
        elif k == "overrides":
            rights["overrides"] = {**(rights.get("overrides") or {}), **v}
        elif not rights.get(k):
            rights[k] = v
    out["rights"] = rights
    return out


def init(pack_id: str, output: str, base: str | None = None) -> list[str]:
    """Start an engagement folder: merged config, inventory, scenarios, questions and the pack README."""
    pack = load(pack_id)
    out = Path(output).expanduser()
    out.mkdir(parents=True, exist_ok=True)
    written = []
    base_cfg = yaml.safe_load(Path(base).read_text(encoding="utf-8")) if base else {}
    cfg = merge(base_cfg or {}, pack["config"])
    header = (f"# Generated by `dpdp-rights packs init {pack_id}` from pack {pack['id']} {pack['version']}"
              f"{' on top of ' + base if base else ''}.\n"
              "# Legal holds and periods are examples: confirm them with counsel before production.\n")
    target = out / "dpdp.yaml"
    if target.exists():
        raise FileExistsError(f"{target} exists; choose another --output or remove it")
    target.write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8")
    written.append(str(target))
    for name in FILES:
        dest = out / (f"PACK-{name}" if name == "README.md" else name)
        if not dest.exists():
            shutil.copyfile(PACK_DIR / pack_id / name, dest)
            written.append(str(dest))
    return written


def test(pack_id: str | None = None, config: str | None = None, scenario_file: str | None = None):
    """Run a pack's scenarios (or a given scenario file) against the pack's settings, or a client's config."""
    from .runner import run

    if config:
        from ..core.config import FrameworkConfig

        fragment = FrameworkConfig.load(config).model_dump(mode="json")
    else:
        fragment = load(pack_id)["config"]
    scn = yaml.safe_load(Path(scenario_file).read_text(encoding="utf-8")) if scenario_file else scenarios(pack_id)
    return run(fragment, scn)
