"""Capability matrix of the connector types: what each can discover, do and verify, and its limits."""
from __future__ import annotations

from ..connectors.base import capability_matrix, load_all_connectors

DISCOVER_LABEL = {"native": "Searches the store", "lineage": "Registered items only"}
DELETION_LABEL = {"item": "yes", "container": "no: whole stream only", "revoke": "no: access revoked instead",
                  "none": "no"}
VERIFY_LABEL = {"rescan": "Rescans for tokens and raw values", "rediscover": "Re-discovery",
                "api_confirmation": "Service confirms", "action_status": "Action status only", "none": "None"}


def load_matrix(include_plugins: bool = True) -> dict[str, dict]:
    if include_plugins:
        load_all_connectors()
    else:
        from ..connectors.base import load_builtin_connectors

        load_builtin_connectors()
    return capability_matrix()


def matrix_markdown(matrix: dict[str, dict] | None = None) -> str:
    matrix = matrix if matrix is not None else load_matrix()
    lines = [
        "| Connector | Store | Finds data | Actions | Individual deletion | Verifies | Limits |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, c in matrix.items():
        limits = "<br>".join(c["limits"]) or "none"
        lines.append(
            f"| `{name}` | {c['store']} | {DISCOVER_LABEL.get(c['discover'], c['discover'])}: {c['discover_how']} "
            f"| {', '.join(c['actions'])} | {DELETION_LABEL.get(c.get('deletion'), c.get('deletion'))} "
            f"| {VERIFY_LABEL.get(c['verify'], c['verify'])}: {c['verify_how']} | {limits} |")
    return "\n".join(lines)


DOC_HEADER = """# Connector capability matrix

<!-- Generated by `dpdp-rights capabilities --format md`. Do not edit by hand: change the connector's
`capabilities` declaration and regenerate (CI checks this file is current). -->

What each connector can find, do and verify, and what the underlying service does not allow. Choose
connectors by capability: a store whose connector cannot delete individual items (logs, traces) is handled
by tokenisation, crypto-shredding and retention instead.

- **Finds data**: *Searches the store* finds a person's data even if nobody registered it with
  `track_artifact`; *Registered items only* acts on what lineage knows about.
- **Actions**: `delete`, `redact` (in place), `regenerate`, `crypto_shred` (make unreadable by destroying
  the key). A connector asked to redact something it can only delete deletes it.
- **Verifies**: how the result is checked after acting.

"""


def capabilities_doc() -> str:
    from .. import plugins
    from ..connectors.base import _REGISTRY

    builtin = {k: v for k, v in load_matrix(include_plugins=False).items()
               if plugins._builtins["connectors"].get(k) is _REGISTRY.get(k)}
    return DOC_HEADER + matrix_markdown(builtin) + "\n"
